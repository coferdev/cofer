#!/usr/bin/env node
// Compiles every .sol under contracts/{src,test,script} with solc-js 0.8.28 (standard JSON),
// fails on any error, and exports ABIs (+ bytecode for parity tests) for the services.
//
//   SOLC_PATH=/path/to/node_modules/solc node contracts/tools/compile.mjs [--only-src]
//
// Works without Foundry or network access.
import { createRequire } from "node:module";
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const solcPath = process.env.SOLC_PATH ?? "solc";
const solc = require(solcPath);

const onlySrc = process.argv.includes("--only-src");
const dirs = onlySrc ? ["src"] : ["src", "test", "script"];

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else if (p.endsWith(".sol")) out.push(p);
  }
  return out;
}

const sources = {};
for (const d of dirs) {
  for (const f of walk(join(root, d))) {
    sources[relative(root, f)] = { content: readFileSync(f, "utf8") };
  }
}

const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "cancun",
    metadata: { bytecodeHash: "ipfs", appendCBOR: true }, // same as foundry.toml (bytecode_hash, cbor_metadata)
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } },
  },
};

function findImports(path) {
  const p = resolve(root, path);
  try {
    return { contents: readFileSync(p, "utf8") };
  } catch {
    return { error: `not found: ${path}` };
  }
}

console.log(`solc ${solc.version()} | ${Object.keys(sources).length} files (${dirs.join(", ")})`);
const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
const errors = (output.errors ?? []).filter((e) => e.severity === "error");
const warnings = (output.errors ?? []).filter((e) => e.severity !== "error");
for (const w of warnings) console.warn(w.formattedMessage);
if (errors.length) {
  for (const e of errors) console.error(e.formattedMessage);
  console.error(`FAILED: ${errors.length} error(s)`);
  process.exit(1);
}

const sizes = [];
for (const [file, contracts] of Object.entries(output.contracts ?? {})) {
  for (const [name, c] of Object.entries(contracts)) {
    const bytes = (c.evm?.deployedBytecode?.object?.length ?? 0) / 2;
    if (bytes > 0 && file.startsWith("src/")) sizes.push(`${name}: ${bytes} B`);
  }
}
console.log("runtime sizes:", sizes.join(" | "));

// Export ABIs + bytecode used by services (and the parity test).
const exportList = {
  CoferPot: "src/CoferPot.sol",
  CoferFactory: "src/CoferFactory.sol",
  FeeRouter: "src/FeeRouter.sol",
  UniV3SwapAdapter: "src/SwapAdapter.sol",
};
const abiDir = resolve(root, "../services/src/chain/abi");
mkdirSync(abiDir, { recursive: true });
for (const [name, file] of Object.entries(exportList)) {
  const c = output.contracts[file]?.[name];
  if (!c) continue;
  writeFileSync(join(abiDir, `${name}.json`), JSON.stringify({ abi: c.abi }, null, 2) + "\n");
}
// Typed ABIs (as const) for viem inference.
const lc = (n) => n.charAt(0).toLowerCase() + n.slice(1);
let ts = "// GENERATED by contracts/tools/compile.mjs: do not edit.\n";
for (const [name, file] of Object.entries(exportList)) {
  const c = output.contracts[file]?.[name];
  if (c) ts += `export const ${lc(name)}Abi = ${JSON.stringify(c.abi)} as const;\n`;
}
writeFileSync(join(abiDir, "index.ts"), ts);
const pot = output.contracts["src/CoferPot.sol"]?.CoferPot;
if (pot) {
  writeFileSync(
    join(abiDir, "CoferPot.bytecode.json"),
    JSON.stringify({ deployedBytecode: "0x" + pot.evm.deployedBytecode.object }) + "\n",
  );
}
console.log(`OK: 0 errors, ${warnings.length} warning(s); ABIs written to services/src/chain/abi`);
